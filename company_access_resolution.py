def pending(c):
    if not PLAN or c.execute('SELECT 1 FROM data_migrations WHERE name=?', (VERSION,)).fetchone():
        return False
    row = c.execute('SELECT value FROM workspace WHERE key=?', (KEY,)).fetchone()
    return bool(row and set(json.loads(row[0]).get('roles', {})) & {p['role'] for p in PLAN})


def apply(c, plan=None):
    c.execute('CREATE TABLE IF NOT EXISTS data_migrations(name TEXT PRIMARY KEY)')
    if c.execute('SELECT 1 FROM data_migrations WHERE name=?', (VERSION,)).fetchone():
        return {'applied': False}
    plan = PLAN if plan is None else plan
    if not plan:
        return {'applied': False}
    row = c.execute('SELECT value FROM workspace WHERE key=?', (KEY,)).fetchone()
    if not row:
        return {'applied': False}
    data = json.loads(row[0])
    if not set(data.get('roles', {})) & {p['role'] for p in plan}:
        return {'applied': False}
    import permissions_policy
    valid = {p['key'] for p in permissions_policy.CATALOG['permissions']}
    if len({(p['role'], p['gate']) for p in plan}) != len(plan):
        raise ValueError('Duplicate access resolution')
    for p in plan:
        prefix = {'is_view': 'is.', 'crm_view': 'crm.'}.get(p['gate'])
        if (not prefix or p['decision'] not in {'enable_access', 'remove_isolated'}
                or not p['permissions'] or set(p['permissions']) - valid
                or any(not code.startswith(prefix) for code in p['permissions'])
                or not p['reason'].strip()):
            raise ValueError('Invalid reviewed access resolution')
    c.execute('SAVEPOINT access_resolution')
    try:
        changed_roles = set()
        added = removed = 0
        outcomes = []
        for p in plan:
            role = p['role']
            if role not in data['roles']:
                outcomes.append({'role': role, 'gate': p['gate'], 'result': 'role no longer exists'})
                continue
            old = set(data['roles'][role])
            new = set(old)
            if p['gate'] in old:
                # An administrator already enabled access; do not remove grants
                # from an otherwise valid role based on the old workbook state.
                result = 'access already enabled; preserved'
            elif not old & set(p['permissions']):
                result = 'affected permissions already removed; preserved'
            elif p['decision'] == 'enable_access':
                new.add(p['gate'])
                result = 'enabled application access'
            else:
                new -= set(p['permissions'])
                result = 'removed isolated permissions'
            if old != new:
                data['roles'][role] = sorted(new)
                changed_roles.add(role)
                added += len(new-old)
                removed += len(old-new)
            outcomes.append({'role': role, 'gate': p['gate'], 'result': result,
                             'added': sorted(new-old), 'removed': sorted(old-new), 'reason': p['reason']})
        if changed_roles:
            c.execute('UPDATE workspace SET value=?,revision=revision+1 WHERE key=?', (json.dumps(data, ensure_ascii=False), KEY))
            affected = {u['id'] for u in data.get('users', []) if u.get('role') in changed_roles}
            for uid in affected:
                c.execute('DELETE FROM sessions WHERE account_id IN (SELECT id FROM accounts WHERE user_id=?)', (uid,))
            for role in changed_roles:
                c.execute('DELETE FROM sessions WHERE account_id IN (SELECT id FROM accounts WHERE role=?)', (role,))
        c.execute('CREATE TABLE IF NOT EXISTS access_resolution_audit(id INTEGER PRIMARY KEY,at TEXT,version TEXT,details TEXT)')
        c.execute('INSERT INTO access_resolution_audit(at,version,details) VALUES(?,?,?)',
                  (datetime.datetime.now(datetime.timezone.utc).isoformat(), VERSION, json.dumps(outcomes, ensure_ascii=False)))
        c.execute('INSERT INTO data_migrations VALUES(?)', (VERSION,))
        c.execute('RELEASE access_resolution')
        return {'applied': True, 'changedRoles': len(changed_roles), 'added': added, 'removed': removed, 'outcomes': outcomes}
    except Exception:
        c.execute('ROLLBACK TO access_resolution')
        c.execute('RELEASE access_resolution')
        raise
